// LocalStorage key for admin and persistence
export const PARTNERS_STORAGE_KEY = 'sahayak_channel_partners';

export function getStoredPartners() {
  try {
    const raw = localStorage.getItem(PARTNERS_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(PARTNERS_STORAGE_KEY, JSON.stringify(initialPartners));
      return initialPartners;
    }
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : initialPartners;
  } catch {
    return initialPartners;
  }
}

export function saveStoredPartners(list) {
  try {
    localStorage.setItem(PARTNERS_STORAGE_KEY, JSON.stringify(list));
  } catch (err) {
    console.error('Failed to save partners', err);
  }
}

